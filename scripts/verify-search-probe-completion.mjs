import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
import ts from "typescript";

const source = fs.readFileSync("scripts/protocol-verify/verify-search-lifecycle.mjs", "utf8");
const ast = ts.createSourceFile("probe.mjs", source, ts.ScriptTarget.Latest, true, ts.ScriptKind.JS);
const helper = ast.statements.find(node => ts.isFunctionDeclaration(node) && node.name?.text === "createSearchCompletion");
assert.ok(helper, "exercise the production probe completion helper without spawning a server");
const create = vm.runInNewContext(`(${helper.getText(ast)})`);
const expected = [{ absPath: "D:/isolated/target-中文-🙂.txt", fileName: "target-中文-🙂.txt" }];
const matches = rows => rows.some(row => row.absPath === expected[0].absPath && row.fileName === expected[0].fileName);
const recorded = () => {
  const values = [], errors = [];
  return { values, errors, listener: create(matches, value => values.push(value), error => errors.push(error)) };
};
const late = recorded();
late.listener.onResults([]); late.listener.onLoading(false);
assert.equal(late.values.length, 0, "completed after initial empty update is not the final expected result");
late.listener.onResults([{ ...expected[0], fileName: "wrong-unicode.txt" }]);
assert.equal(late.values.length, 0, "completion cannot relax exact Unicode expectation");
late.listener.onResults([{ ...expected[0], absPath: "D:/other/target-中文-🙂.txt" }]);
assert.equal(late.values.length, 0, "completion cannot relax exact workspace target expectation");
late.listener.onResults(expected);
assert.deepEqual(late.values, [expected], "late update completes the already-completed session without sleeps");
late.listener.onResults(expected); assert.equal(late.values.length, 1, "completion settles once");
const early = recorded(); early.listener.onLoading(false);
assert.equal(early.values.length, 0, "completed signal alone cannot fabricate empty results");
early.listener.onResults(expected); assert.deepEqual(early.values, [expected]);
const ordered = recorded(); ordered.listener.onResults(expected);
assert.equal(ordered.values.length, 0, "matching results must also await completion");
ordered.listener.onLoading(true); assert.equal(ordered.values.length, 0);
ordered.listener.onLoading(false); assert.deepEqual(ordered.values, [expected]);
const failed = recorded(); const error = Error("real backend failure");
failed.listener.onError(error); failed.listener.onResults(expected); failed.listener.onLoading(false);
assert.deepEqual(failed.errors, [error]); assert.equal(failed.values.length, 0, "errors must not later turn into passing results");
const deleted = [];
const removal = create(rows => rows.length === 0, value => deleted.push(value), error => { throw error; });
removal.onLoading(false); assert.equal(deleted.length, 0, "deletion also needs a real result callback");
removal.onResults([]); assert.equal(deleted.length, 1);
console.log("PASS production probe completion: initial-empty/completed/late-update, strict path+Unicode, reverse order, once, real failure and deletion callbacks");
