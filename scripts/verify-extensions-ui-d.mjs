import assert from "node:assert/strict";
import { harness } from "./verify-plugin-management-ui-b.mjs";

const h = harness();
h.props.manageOnly = false;
h.props.initialTab = "skills";
h.render(); await h.tick();
assert.deepEqual(h.tabs().map(node => h.text(node).replace(/ \(\d+\)$/, "")), ["插件", "技能"], "directory must not merge management surfaces");
assert.equal(h.nodes(h.tree).find(node => node.type === "h2")?.children[0], "技能");
assert.ok(h.text(h.tree).includes("通过任务专用技能扩展 Codex"));
assert.equal(h.nodes(h.tree).filter(node => node.type === "textarea").length, 0, "directory initial state has no blank editor");
assert.equal(h.nodes(h.tree).filter(node => node.type === "button" && h.text(node).includes("连接至自定义 MCP")).length, 0);
const row = h.nodes(h.tree).find(node => node.props.className?.includes("skill-list-row"));
assert.equal(row.props.role, "button");
assert.equal(row.props.tabIndex, 0);
const overviewIndex = h.nodes(h.tree).findIndex(node => node.props.className?.includes("pm-skills-overview"));
const recommendedIndex = h.nodes(h.tree).findIndex(node => typeof node.props.beginInstall === "function");
assert.ok(overviewIndex >= 0 && recommendedIndex > overviewIndex, "installed skills precede recommendations");
const toggle = h.nodes(row).find(node => node.props.role === "switch");
assert.equal(toggle, undefined, "directory uses the evidenced check state; preview header owns the toggle");
assert.ok(h.nodes(row).some(node => node.props["aria-label"] === "技能已启用"));
let childPrevented = false;
row.props.onKeyDown({key:" ", target:{}, currentTarget:row, preventDefault(){childPrevented = true;}});
assert.equal(childPrevented, false, "nested switch keys must not also select the row");
let prevented = false;
row.props.onKeyDown({key:"Enter", preventDefault(){prevented = true;}});
await h.tick(); assert.ok(prevented);
assert.equal(h.nodes(h.tree).filter(node => node.type === "textarea").length, 0, "installed selection opens a separate read-only preview");
assert.ok(h.nodes(h.tree).some(node => node.type === "SkillPreviewDialog"), "selection keeps genuine skill contents accessible through preview");
const draft = harness(); draft.props.manageOnly = false; draft.props.initialTab = "skills";
draft.render(); await draft.tick();
draft.button("本地模版").props.onClick(); draft.render();
let draftTextarea = draft.nodes(draft.tree).find(node => node.type === "textarea");
draftTextarea.props.onChange({target:{value:"unsaved meaningful draft"}}); draft.render();
let idInput = draft.nodes(draft.tree).find(node => node.type === "input" && node.props.placeholder === "skill-folder-name");
idInput.props.onChange({target:{value:""}}); draft.render();
draftTextarea = draft.nodes(draft.tree).find(node => node.type === "textarea");
assert.ok(draftTextarea, "clearing a new skill id cannot unmount its draft editor");
assert.equal(draftTextarea.props.value, "unsaved meaningful draft");
assert.equal(draft.button("保存 SKILL.md").props.disabled, true);
idInput = draft.nodes(draft.tree).find(node => node.type === "input" && node.props.placeholder === "skill-folder-name");
idInput.props.onChange({target:{value:"replacement-id"}}); draft.render();
assert.equal(draft.nodes(draft.tree).find(node => node.type === "textarea").props.value, "unsaved meaningful draft");
draft.unmount();
const p = harness({ plugins: { pluginRefFor: () => ({}), readPlugin: async () => { throw Error("isolated detail unavailable"); } } }); p.render(); await p.tick();
const detail = p.nodes(p.tree).find(node => node.type === "button" && node.props.className === "pm-managed-plugin-open");
assert.ok(detail, "plugin title must be a keyboard-operable button");
assert.ok(!detail.props.title?.includes("plugin/read"));
await detail.props.onClick(); await p.tick();
assert.ok(p.nodes(p.tree).some(node => node.props["aria-label"] === "插件管理详情"), "management opens an independent detail surface");
assert.ok(p.text(p.tree).includes("读取详情失败"), "detail transport failure remains visible");
p.backManagedDetail(); await p.tick();
assert.ok(p.nodes(p.tree).some(node => node.type === "button" && node.props.className === "pm-managed-plugin-open"), "back restores the actionable compact row");
assert.equal(p.calls.filter(call => ["toggle", "run"].includes(call[0])).length, 0, "opening details cannot mutate installation");
assert.equal(p.tabs().length, 5, "runtime management tabs remain available");
const directory = harness();
let managementVisits = 0;
directory.props.manageOnly = false;
directory.props.initialTab = "plugins";
directory.props.onManagePlugins = () => { managementVisits++; };
directory.render(); await directory.tick();
const manage = directory.nodes(directory.tree).find(node => node.type === "button" && directory.text(node).trim() === "管理");
assert.ok(manage, "plugin directory exposes the real management entry");
const callsBeforeNavigation = directory.calls.length;
manage.props.onClick();
assert.equal(managementVisits, 1, "manage activation navigates once");
assert.equal(directory.calls.length, callsBeforeNavigation, "manage cannot install, authorize or mutate");
directory.button("技能 (1)").props.onClick(); directory.render();
assert.ok(!directory.nodes(directory.tree).some(node => node.type === "button" && directory.text(node).trim() === "管理"), "plugin management is scoped to plugins");
assert.ok(!p.nodes(p.tree).some(node => node.type === "button" && p.text(node).trim() === "管理"), "management page cannot recurse into itself");
directory.unmount(); h.unmount(); p.unmount();
console.log("PASS extensions directory/management boundary and skill keyboard access");
