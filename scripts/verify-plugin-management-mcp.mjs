import assert from "node:assert/strict";
import fs from "node:fs";
import vm from "node:vm";
import ts from "typescript";
const exports = {};
vm.runInNewContext(ts.transpileModule(fs.readFileSync("src/pluginManagementMcp.ts", "utf8"), {
  compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS },
}).outputText, { exports });
const { canonicalMcpAppId: canonical, resolvePluginMcpRows: rows } = exports;
assert.equal(canonical("asdk_app_ABC"), "connector_ABC");
assert.equal(canonical("ASDK_app_ABC"), "ASDK_app_ABC");
const detail = { summary: { version: "1" }, apps: [{id:"asdk_app_A"}], mcpServers:["connector_Test-App", "mcp_One", "missing"] };
const app = {id:"connector_A", name:"Test App",pluginDisplayNames:[],labels:{}};
const config = {mcp_servers:{"actual.key":{name:"One",enabled:false}, "later":{name:"mcp_One",enabled:true}}};
let result=rows(detail,config,[app]);
assert.equal(result[0].kind,"app");
assert.equal(result[0].app,app);
assert.equal(result[1].configKey,"actual.key","first normalized match writes actual config key, not declared name");
assert.equal(result[1].enabled,false);
assert.equal(result[2].configKey,null);
assert.equal(result[2].enabled,true);
assert.equal(rows(detail,config,[{...app,id:"other"}])[0].kind,"app","official MCP matcher receives the complete directoryApps, not only declared plugin apps");
const withManifest=apps=>({...detail,summary:{version:"1",remoteServicePlugin:{release:{version:"1",app_manifest:{apps}}}}});
assert.equal(rows(withManifest({}),config,[app])[0].kind,"config","present empty manifest suppresses heuristic");
assert.equal(rows(withManifest({"connector_Test-App":{id:"asdk_app_A"}}),config,[app])[0].kind,"app");
assert.equal(rows(withManifest({"connector_test-app":{id:"asdk_app_A"}}),config,[app])[0].kind,"config","manifest keys are exact");
const stale=withManifest({});stale.summary.version="0";
assert.equal(rows(stale,config,[app])[0].kind,"app","different version does not borrow latest manifest");
const unknown=withManifest({});unknown.summary.version=null;
assert.equal(rows(unknown,config,[app])[0].kind,"app","unknown installed version is not a matching release");
assert.equal(rows({...detail,mcpServers:["mcp_connector_One"]},config,[])[0].configKey,null,"prefix order is not recursive");
assert.equal(rows({...detail,mcpServers:["a.b"]},{mcp_servers:{"a-b":{}}},[])[0].configKey,null,"dots remain significant");
assert.equal(rows({...detail,mcpServers:["MCP-One"]},{mcpServers:{"real":{name:"mcp_one"}}},[])[0].configKey,"real");
assert.equal(rows({...detail,mcpServers:["mcp_One"]},{mcp_servers:{real:null}},[])[0].configKey,null);
assert.equal(rows({...detail,mcpServers:["real"]},{mcp_servers:{real:null}},[])[0].configKey,"real");
assert.equal(rows(detail,[],[]).length,3);
assert.equal(rows({...detail,mcpServers:["real"]},{mcp_servers:[],mcpServers:{real:{}}},[])[0].configKey,null,"invalid present snake-case map does not fall through to camel-case");
assert.equal(rows(detail,config,[{...app,name:"different",labels:{"Test App":"label"}}])[0].kind,"app","label keys participate");
console.log("Plugin management MCP mapping: canonical IDs, complete directory, manifest/version precedence, prefix order and exact config keys passed.");
